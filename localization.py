ENGLISH_TO_ARABIC = {english: arabic for arabic, english in ARABIC_TO_ENGLISH.items()}


def translate(text, language):
    if not isinstance(text, str):
        return text
    if language == "en":
        if text in ARABIC_TO_ENGLISH:
            return ARABIC_TO_ENGLISH[text]
        for arabic, english in sorted(ARABIC_TO_ENGLISH.items(), key=lambda item: len(item[0]), reverse=True):
            if arabic and arabic in text:
                text = text.replace(arabic, english)
        return text
    if text in ENGLISH_TO_ARABIC:
        return ENGLISH_TO_ARABIC[text]
    for english, arabic in sorted(ENGLISH_TO_ARABIC.items(), key=lambda item: len(item[0]), reverse=True):
        if english and english in text:
            text = text.replace(english, arabic)
    return text
